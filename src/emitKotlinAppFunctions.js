/**
 * src/emitKotlinAppFunctions.js
 * Target 5: Google Android 16+ AppFunctions (Jetpack @RequiresApi(36))
 */

import { toPascalCase, toCamelCase } from './validateContracts.js';

function mapKotlinScalar(prop, isRequired) {
  let kt = 'String';
  if (prop.type === 'integer') kt = 'Int';
  else if (prop.type === 'number') kt = 'Double';
  else if (prop.type === 'boolean') kt = 'Boolean';
  return isRequired || prop.default !== undefined ? kt : `${kt}? = null`;
}

export function emitKotlinAppFunctions(scaffold) {
  const androidActions = scaffold.actions.filter((a) =>
    a.governance.surfaces.includes('android_app_functions')
  );

  const pkg = `${scaffold.bundleId?.android ?? `com.openscaffoldlabs.${scaffold.appId.replace(/-/g, '')}`}.appfunctions`;
  const servicePrefix = toPascalCase(scaffold.appId);
  const xmlFileName = `${scaffold.appId.replace(/-/g, '_')}_app_functions`;

  const lines = [
    `// Generated by @openscaffold/compiler v1.0.0 for ${scaffold.displayName} — DO NOT EDIT`,
    `package ${pkg}`,
    '',
    'import androidx.annotation.RequiresApi',
    'import androidx.appfunctions.AppFunctionDeclaration',
    'import androidx.appfunctions.AppFunctionInvalidArgumentException',
    'import androidx.appfunctions.AppFunctionSerializable',
    'import androidx.appfunctions.AppFunctionService',
    'import androidx.appfunctions.AppFunctionServiceEntryPoint',
    'import kotlinx.coroutines.Dispatchers',
    'import kotlinx.coroutines.withContext',
    '',
  ];

  for (const action of androidActions) {
    const pascalAction = toPascalCase(action.id.split('.')[1]);
    const props = action.input?.properties ?? {};
    const requiredSet = new Set(action.input?.required ?? []);

    lines.push(`/** Input parameters for ${action.title}. */`);
    lines.push('@AppFunctionSerializable(isDescribedByKDoc = true)');
    lines.push(`data class ${pascalAction}Params(`);
    for (const [propName, prop] of Object.entries(props)) {
      const isIdemp = propName === action.ledger?.idempotencyKeyField;
      const isReq = isIdemp ? false : requiredSet.has(propName);
      const decl = isIdemp
        ? 'String? = null'
        : prop.default !== undefined
        ? `${mapKotlinScalar(prop, true)} = ${typeof prop.default === 'string' ? `"${prop.default}"` : prop.default}`
        : mapKotlinScalar(prop, isReq);
      lines.push(`    /** ${prop.description || prop.title || propName} */`);
      lines.push(`    val ${toCamelCase(propName)}: ${decl},`);
    }
    lines.push(')');
    lines.push('');

    lines.push(`/** Result payload for ${action.title}. */`);
    lines.push('@AppFunctionSerializable(isDescribedByKDoc = true)');
    lines.push(`data class ${pascalAction}Result(`);
    const outProps = action.output?.properties ?? { status: { type: 'string', title: 'Status' } };
    const outReq = new Set(action.output?.required ?? Object.keys(outProps));
    for (const [oName, oProp] of Object.entries(outProps)) {
      lines.push(`    /** ${oProp.description || oProp.title || oName} */`);
      lines.push(`    val ${toCamelCase(oName)}: ${mapKotlinScalar(oProp, outReq.has(oName))},`);
    }
    lines.push(')');
    lines.push('');
  }

  lines.push('@RequiresApi(36)');
  lines.push('@AppFunctionServiceEntryPoint(');
  lines.push(`    serviceName = "${servicePrefix}AppFunctionService",`);
  lines.push(`    appFunctionXmlFileName = "${xmlFileName}",`);
  lines.push(')');
  lines.push(`abstract class Base${servicePrefix}AppFunctionService : AppFunctionService() {`);
  lines.push('');

  for (const action of androidActions) {
    const shortName = action.id.split('.')[1];
    const fnName = toCamelCase(shortName);
    const pascalAction = toPascalCase(shortName);
    const props = action.input?.properties ?? {};

    lines.push('    /**');
    lines.push(`     * ${action.description || action.summary}`);
    lines.push(`     * Governance commitMode: ${action.governance.commitMode}.`);
    lines.push('     *');
    lines.push(`     * @param params Typed parameters for ${action.title}.`);
    lines.push(`     * @return Result summary for ${action.title}.`);
    lines.push('     */');
    lines.push('    @AppFunctionDeclaration(isDescribedByKDoc = true)');
    lines.push(`    suspend fun ${fnName}(params: ${pascalAction}Params): ${pascalAction}Result =`);
    lines.push('        withContext(Dispatchers.IO) {');

    for (const [propName, prop] of Object.entries(props)) {
      const camel = toCamelCase(propName);
      if (prop.type === 'integer' && prop.minimum !== undefined && prop.maximum !== undefined) {
        lines.push(`            if (params.${camel} !in ${prop.minimum}..${prop.maximum}) {`);
        lines.push(
          `                throw AppFunctionInvalidArgumentException("${camel} must be between ${prop.minimum} and ${prop.maximum}.")`
        );
        lines.push('            }');
      }
      if (Array.isArray(prop.enum) && prop.enum.length > 0) {
        const setVals = prop.enum.map((v) => `"${v}"`).join(', ');
        lines.push(`            if (params.${camel} !in setOf(${setVals})) {`);
        lines.push(
          `                throw AppFunctionInvalidArgumentException("${camel} must be one of: ${prop.enum.join(', ')}")`
        );
        lines.push('            }');
      }
    }

    lines.push('            OslActionGateway.invoke(');
    lines.push(`                contractId = "${action.id}",`);
    lines.push('                surface = "android-appfunction",');
    lines.push(`                commitMode = "${action.governance.commitMode}",`);
    lines.push('                payload = params');
    lines.push('            )');
    lines.push('        }');
    lines.push('');
  }

  lines.push('}');

  const xmlManifest = [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<app-functions package="${pkg}" version="${scaffold.version}">`,
    ...androidActions.map(
      (a) =>
        `  <app-function id="${a.id}" method="${toCamelCase(a.id.split('.')[1])}" commitMode="${a.governance.commitMode}" readOnly="${a.semantics.readOnly}" />`
    ),
    '</app-functions>',
  ].join('\n');

  return { kotlinSource: lines.join('\n'), xmlManifest };
}
