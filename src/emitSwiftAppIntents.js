/**
 * src/emitSwiftAppIntents.js
 * Target 4: Apple Siri AI App Intents (Swift 6 / iOS, iPadOS, macOS, visionOS 27.3+)
 */

import { toPascalCase, toCamelCase } from './validateContracts.js';

function resolveSwiftParamType(propName, prop, actionShort) {
  if (prop.entityRef) {
    return `${toPascalCase(prop.entityRef)}Entity`;
  }
  if (Array.isArray(prop.enum) && prop.enum.length > 0) {
    return `${toPascalCase(actionShort)}${toPascalCase(propName)}AppEnum`;
  }
  if (prop.type === 'integer') return 'Int';
  if (prop.type === 'number') return 'Double';
  if (prop.type === 'boolean') return 'Bool';
  return 'String';
}

export function emitSwiftAppIntents(scaffold) {
  const iosActions = scaffold.actions.filter((a) =>
    a.governance.surfaces.includes('apple_app_intents')
  );

  const lines = [
    `// Generated by @openscaffold/compiler v1.0.0 for ${scaffold.displayName} — DO NOT EDIT`,
    'import AppIntents',
    'import Foundation',
    '',
  ];

  for (const [entityKey, entity] of Object.entries(scaffold.entities ?? {})) {
    const structName = `${toPascalCase(entityKey)}Entity`;
    lines.push(`struct ${structName}: AppEntity {`);
    lines.push(
      `    static let typeDisplayRepresentation: TypeDisplayRepresentation = "${entity.title || entityKey}"`
    );
    lines.push(`    static let defaultQuery = ${structName}Query()`);
    lines.push('    var id: String');
    for (const [pName, pDef] of Object.entries(entity.properties ?? {})) {
      if (pName === 'id') continue;
      const pType =
        pDef.type === 'integer'
          ? 'Int'
          : pDef.type === 'number'
          ? 'Double'
          : pDef.type === 'boolean'
          ? 'Bool'
          : 'String';
      lines.push(`    @Property(title: "${pDef.title || pName}") var ${toCamelCase(pName)}: ${pType}`);
    }
    lines.push('    var displayRepresentation: DisplayRepresentation {');
    lines.push('        DisplayRepresentation(title: "\\(id)")');
    lines.push('    }');
    lines.push('}');
    lines.push('');
  }

  for (const action of iosActions) {
    const actionShort = action.id.split('.')[1];
    const intentStruct = `${toPascalCase(actionShort)}Intent`;
    const props = action.input?.properties ?? {};
    const requiredSet = new Set(action.input?.required ?? []);

    for (const [propName, prop] of Object.entries(props)) {
      if (Array.isArray(prop.enum) && prop.enum.length > 0) {
        const enumName = resolveSwiftParamType(propName, prop, actionShort);
        lines.push(`enum ${enumName}: String, AppEnum {`);
        for (const val of prop.enum) {
          lines.push(`    case ${toCamelCase(val)} = "${val}"`);
        }
        lines.push(
          `    static let typeDisplayRepresentation: TypeDisplayRepresentation = "${prop.title || propName}"`
        );
        lines.push(`    static let caseDisplayRepresentations: [${enumName}: DisplayRepresentation] = [`);
        for (const val of prop.enum) {
          lines.push(`        .${toCamelCase(val)}: "${val.replace(/_/g, ' ')}",`);
        }
        lines.push('    ]');
        lines.push('}');
        lines.push('');
      }
    }

    lines.push('@available(iOS 27.3, iPadOS 27.3, macOS 27.3, visionOS 27.3, *)');
    if (action.governance.commitMode !== 'queue_peer_accept') {
      lines.push('@AppIntent(.tool)');
    }
    lines.push(`struct ${intentStruct}: AppIntent {`);
    lines.push(`    static let title: LocalizedStringResource = "${action.title}"`);
    lines.push(
      `    static let description = IntentDescription("${(action.description || action.summary || '').replace(/"/g, '\\"')}")`
    );
    lines.push('');

    const payloadPairs = [];
    for (const [propName, prop] of Object.entries(props)) {
      if (propName === action.ledger?.idempotencyKeyField) {
        payloadPairs.push(`"${propName}": UUID().uuidString.lowercased()`);
        continue;
      }
      const swiftVar = toCamelCase(propName);
      const baseType = resolveSwiftParamType(propName, prop, actionShort);
      const isOptional = !requiredSet.has(propName) && prop.default === undefined;
      const swiftType = isOptional ? `${baseType}?` : baseType;

      const attrParts = [
        `title: "${prop.title || propName}"`,
        `description: "${(prop.description || '').replace(/"/g, '\\"')}"`,
      ];
      if (prop.default !== undefined) {
        attrParts.push(
          `default: ${typeof prop.default === 'string' ? `"${prop.default}"` : prop.default}`
        );
      }
      if (prop.type === 'integer' && prop.minimum !== undefined && prop.maximum !== undefined) {
        attrParts.push(`inclusiveRange: (${prop.minimum}, ${prop.maximum})`);
      }

      lines.push(`    @Parameter(${attrParts.join(', ')})`);
      lines.push(`    var ${swiftVar}: ${swiftType}`);
      lines.push('');

      if (prop.entityRef) {
        payloadPairs.push(`"${propName}": ${swiftVar}${isOptional ? '?' : ''}.id as Any`);
      } else if (Array.isArray(prop.enum)) {
        payloadPairs.push(`"${propName}": ${swiftVar}${isOptional ? '?' : ''}.rawValue as Any`);
      } else {
        payloadPairs.push(`"${propName}": ${swiftVar} as Any`);
      }
    }

    lines.push('    func perform() async throws -> some IntentResult & ProvidesDialog {');
    if (action.governance.commitMode === 'approve_1tap') {
      lines.push('        try await requestConfirmation(');
      lines.push(`            result: .result(dialog: "Approve ${action.title}?")`);
      lines.push('        )');
    }
    lines.push('        let response = try await OSLActionTransport.shared.invoke(');
    lines.push(`            contractId: "${action.id}",`);
    lines.push('            surface: "apple-siri-tool",');
    lines.push(`            payload: [${payloadPairs.join(', ')}]`);
    lines.push('        )');
    lines.push('        return .result(dialog: "\\(response.spokenSummary)")');
    lines.push('    }');
    lines.push('}');
    lines.push('');
  }

  const skillMarkdown = [
    '---',
    `name: ${scaffold.appId}-siri-skill`,
    `description: Guidance for Siri AI when orchestrating ${scaffold.displayName} tools.`,
    '---',
    `# ${scaffold.displayName} Siri AI Skill`,
    '',
    ...iosActions.map(
      (a) =>
        `- **${toPascalCase(a.id.split('.')[1])}Intent** (\`${a.governance.commitMode}\`): ${a.summary || a.description}`
    ),
  ].join('\n');

  return { swiftSource: lines.join('\n'), skillMarkdown };
}
